import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import Ajv from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standalone from "ajv/dist/standalone/index.js";
import { build } from "esbuild";

const root = fileURLToPath(new URL("../", import.meta.url));
const schema = JSON.parse(await fs.readFile(path.join(root, "docs/api/v1/review-schema.json"), "utf8"));
const ajv = new Ajv({ strict: true, code: { source: true, esm: true } });
addFormats(ajv);
const source = standalone(ajv, ajv.compile(schema));
const result = await build({
  stdin: { contents: source, resolveDir: root, sourcefile: "review-validator.mjs", loader: "js" },
  bundle: true, platform: "browser", format: "esm", target: "es2022", write: false,
  banner: { js: "// Generated by Ajv + esbuild from docs/api/v1/review-schema.json; do not edit." },
});
const generated = result.outputFiles[0].text;
const output = path.join(root, "docs/assets/review/contract.mjs");
if (process.argv.includes("--check")) {
  // Git may check out text as CRLF on Windows; line endings do not change the schema.
  const current = (await fs.readFile(output, "utf8")).replaceAll("\r\n", "\n");
  if (current !== generated.replaceAll("\r\n", "\n")) {
    throw new Error("Review validator is stale: run npm run build:review-schema");
  }
} else {
  await fs.writeFile(output, generated);
}
